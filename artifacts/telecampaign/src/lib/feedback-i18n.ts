/** Convert server/processing errors to canonical keys so an open alert switches language too. */
export function feedbackErrorKey(error: unknown, fallback = "Could not complete this action. Please try again."): string {
  const message = error instanceof Error ? error.message : "";
  if (Object.hasOwn(feedbackTranslations, message)) return message;
  return Object.hasOwn(feedbackServerErrors, message) ? feedbackServerErrors[message] : fallback;
}
